-- Actividades para casa, entregas y notificaciones push.

create table public.actividades_aprendizaje (
    id bigint generated by default as identity primary key,
    institucion_id bigint not null references public.instituciones_educativas(id),
    anio_escolar_id bigint not null references public.anios_escolares(id),
    experiencia_id bigint references public.experiencias_aprendizaje(id),
    sesion_planificada_id bigint references public.sesiones_planificadas(id),
    area_curricular_id bigint references public.areas_curriculares(id),
    titulo varchar(240) not null,
    instrucciones text not null,
    tipo varchar(30) not null default 'OTRA'
        check (tipo in ('LECTURA', 'PRACTICA', 'FICHA', 'PROYECTO', 'OBSERVACION', 'OTRA')),
    formato_entrega varchar(24) not null default 'NO_REQUIERE'
        check (formato_entrega in ('NO_REQUIERE', 'ARCHIVO', 'PAPEL', 'ORAL', 'EN_CLASE', 'OTRO')),
    requiere_entrega boolean not null default false,
    publicada_at timestamptz,
    fecha_limite timestamptz,
    estado varchar(20) not null default 'BORRADOR'
        check (estado in ('BORRADOR', 'PUBLICADA', 'CERRADA', 'ANULADA')),
    creada_por bigint not null references public.cuentas_usuario(id),
    created_at timestamptz not null default now(),
    check (fecha_limite is null or publicada_at is null or fecha_limite >= publicada_at),
    check ((requiere_entrega and formato_entrega <> 'NO_REQUIERE') or
           (not requiere_entrega and formato_entrega = 'NO_REQUIERE'))
);

create table public.destinos_actividad (
    id bigint generated by default as identity primary key,
    actividad_id bigint not null references public.actividades_aprendizaje(id),
    seccion_id bigint references public.secciones(id),
    matricula_id bigint references public.matriculas(id),
    check (num_nonnulls(seccion_id, matricula_id) = 1),
    unique nulls not distinct (actividad_id, seccion_id, matricula_id)
);

create table public.asignaciones_actividad (
    id bigint generated by default as identity primary key,
    actividad_id bigint not null references public.actividades_aprendizaje(id),
    matricula_id bigint not null references public.matriculas(id),
    estado varchar(32) not null default 'PENDIENTE'
        check (estado in (
            'PENDIENTE', 'ENTREGADA', 'ENTREGADA_TARDE', 'REVISADA',
            'NO_ENTREGADA_CONFIRMADA', 'EXENTA', 'NO_REQUIERE_ENTREGA'
        )),
    estado_confirmado_por bigint references public.cuentas_usuario(id),
    estado_confirmado_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check ((estado = 'NO_ENTREGADA_CONFIRMADA' and estado_confirmado_por is not null)
           or estado <> 'NO_ENTREGADA_CONFIRMADA'),
    unique (actividad_id, matricula_id)
);

create table public.archivos (
    id bigint generated by default as identity primary key,
    bucket varchar(80) not null,
    ruta_objeto text not null,
    nombre_original varchar(255) not null,
    tipo_contenido varchar(120),
    tamano_bytes bigint check (tamano_bytes is null or tamano_bytes >= 0),
    creado_por bigint references public.cuentas_usuario(id),
    created_at timestamptz not null default now(),
    unique (bucket, ruta_objeto)
);

create table public.entregas_actividad (
    id bigint generated by default as identity primary key,
    asignacion_actividad_id bigint not null references public.asignaciones_actividad(id),
    numero_intento smallint not null default 1 check (numero_intento > 0),
    formato varchar(24) not null check (formato in ('ARCHIVO', 'PAPEL', 'ORAL', 'EN_CLASE', 'OTRO')),
    contenido text,
    archivo_id bigint references public.archivos(id),
    registrada_por bigint not null references public.cuentas_usuario(id),
    entregada_at timestamptz not null default now(),
    unique (asignacion_actividad_id, numero_intento)
);

create table public.revisiones_actividad (
    id bigint generated by default as identity primary key,
    entrega_id bigint not null references public.entregas_actividad(id),
    revisada_por bigint not null references public.cuentas_usuario(id),
    comentario text,
    revisada_at timestamptz not null default now()
);

create table public.tipos_notificacion (
    id smallint generated by default as identity primary key,
    codigo varchar(40) not null unique,
    nombre varchar(120) not null,
    activa boolean not null default true
);

