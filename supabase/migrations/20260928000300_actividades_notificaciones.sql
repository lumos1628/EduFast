create table public.preferencias_notificacion (
    id bigint generated by default as identity primary key,
    cuenta_usuario_id bigint not null references public.cuentas_usuario(id),
    tipo_notificacion_id smallint not null references public.tipos_notificacion(id),
    canal varchar(24) not null check (canal in ('ANDROID_PUSH', 'WEB_PUSH', 'EMAIL', 'SMS')),
    habilitada boolean not null default true,
    hora_silencio_inicio time,
    hora_silencio_fin time,
    unique (cuenta_usuario_id, tipo_notificacion_id, canal)
);

create table public.dispositivos_notificacion (
    id bigint generated by default as identity primary key,
    cuenta_usuario_id bigint not null references public.cuentas_usuario(id),
    plataforma varchar(20) not null check (plataforma in ('ANDROID', 'WEB', 'IOS')),
    token_registro text not null unique,
    permiso_habilitado boolean not null default true,
    activo boolean not null default true,
    ultimo_uso_at timestamptz,
    registrado_at timestamptz not null default now(),
    revocado_at timestamptz
);

create table public.eventos_notificacion (
    id bigint generated by default as identity primary key,
    tipo_notificacion_id smallint not null references public.tipos_notificacion(id),
    registro_asistencia_id bigint references public.registros_asistencia(id),
    actividad_id bigint references public.actividades_aprendizaje(id),
    asignacion_actividad_id bigint references public.asignaciones_actividad(id),
    version_origen integer not null default 1 check (version_origen > 0),
    clave_idempotencia varchar(180) not null unique,
    datos_minimos jsonb not null default '{}'::jsonb,
    estado varchar(20) not null default 'PENDIENTE'
        check (estado in ('PENDIENTE', 'PROCESANDO', 'PROCESADO', 'FALLIDO', 'CANCELADO')),
    creado_at timestamptz not null default now(),
    procesado_at timestamptz,
    check (num_nonnulls(registro_asistencia_id, actividad_id, asignacion_actividad_id) = 1)
);

create table public.notificaciones (
    id bigint generated by default as identity primary key,
    evento_id bigint not null references public.eventos_notificacion(id),
    vinculo_apoderado_estudiante_id bigint not null references public.vinculos_apoderado_estudiante(id),
    cuenta_destinataria_id bigint references public.cuentas_usuario(id),
    titulo varchar(180) not null,
    mensaje varchar(500) not null,
    ruta_destino text,
    creada_at timestamptz not null default now(),
    leida_at timestamptz,
    unique (evento_id, vinculo_apoderado_estudiante_id)
);

create table public.entregas_notificacion (
    id bigint generated by default as identity primary key,
    notificacion_id bigint not null references public.notificaciones(id),
    dispositivo_id bigint references public.dispositivos_notificacion(id),
    canal varchar(24) not null check (canal in ('ANDROID_PUSH', 'WEB_PUSH', 'EMAIL', 'SMS')),
    estado varchar(20) not null default 'EN_COLA'
        check (estado in ('EN_COLA', 'ACEPTADA', 'ENTREGADA', 'FALLIDA', 'EXPIRADA', 'CANCELADA')),
    proveedor varchar(40),
    identificador_proveedor varchar(180),
    expira_at timestamptz,
    aceptada_at timestamptz,
    entregada_at timestamptz,
    ultimo_error text,
    unique (notificacion_id, dispositivo_id, canal)
);

create table public.intentos_notificacion (
    id bigint generated by default as identity primary key,
    entrega_notificacion_id bigint not null references public.entregas_notificacion(id),
    numero_intento smallint not null check (numero_intento > 0),
    resultado varchar(20) not null check (resultado in ('ACEPTADO', 'ENTREGADO', 'FALLIDO')),
    codigo_respuesta varchar(100),
    detalle text,
    intentado_at timestamptz not null default now(),
    unique (entrega_notificacion_id, numero_intento)
);

create table public.eventos_auditoria (
    id bigint generated by default as identity primary key,
    cuenta_usuario_id bigint references public.cuentas_usuario(id),
    institucion_id bigint references public.instituciones_educativas(id),
    tipo_evento varchar(80) not null,
    tipo_objeto varchar(80) not null,
    objeto_id bigint not null,
    datos_minimos jsonb not null default '{}'::jsonb,
    ocurrido_at timestamptz not null default now()
);

-- Los clientes no consultan Postgres directamente. El backend es el único acceso
-- de aplicación; se habilita RLS y no se conceden permisos al API anon/authenticated.
do $$
declare
    tabla record;
begin
    for tabla in
        select tablename
        from pg_tables
        where schemaname = 'public'
          and tablename in (
              'instituciones_educativas', 'sedes_educativas', 'niveles_educativos',
              'ciclos_educativos', 'grados_educativos', 'turnos', 'anios_escolares',
              'periodos_evaluacion', 'aulas', 'personas', 'cuentas_usuario', 'roles',
              'estudiantes', 'apoderados', 'contactos_persona', 'niveles_notificacion',
              'secciones', 'asignaciones_roles', 'vinculos_apoderado_estudiante',
              'matriculas', 'ubicaciones_matricula', 'movimientos_matricula',
              'asignaciones_docentes', 'jornadas_asistencia', 'registros_asistencia',
              'versiones_curriculares', 'areas_curriculares', 'version_areas_curriculares',
              'competencias', 'competencias_areas', 'capacidades', 'estandares_aprendizaje',
              'desempenos_grado', 'planes_estudio', 'planes_estudio_areas',
              'ofertas_curriculares', 'asignaciones_docentes_areas', 'eventos_calendario',
              'planificaciones_anuales', 'destinos_planificacion', 'experiencias_aprendizaje',
              'experiencias_competencias', 'criterios_evaluacion', 'instrumentos_evaluacion',
              'criterios_instrumento', 'niveles_instrumento', 'sesiones_planificadas',
              'sesiones_competencias', 'actividades_sesion', 'evidencias_previstas',
              'ejecuciones_sesion', 'evidencias_aprendizaje', 'valoraciones_evidencia',
              'retroalimentaciones', 'progreso_competencias', 'actividades_aprendizaje',
              'destinos_actividad', 'asignaciones_actividad', 'archivos', 'entregas_actividad',
              'revisiones_actividad', 'tipos_notificacion', 'preferencias_notificacion',
              'dispositivos_notificacion', 'eventos_notificacion', 'notificaciones',
              'entregas_notificacion', 'intentos_notificacion',
              'eventos_auditoria'
          )
    loop
        execute format('alter table public.%I enable row level security', tabla.tablename);
    end loop;
end $$;

do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon') then
        execute 'revoke all on all tables in schema public from anon';
        execute 'revoke all on all sequences in schema public from anon';
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
        execute 'revoke all on all tables in schema public from authenticated';
        execute 'revoke all on all sequences in schema public from authenticated';
    end if;
end $$;
