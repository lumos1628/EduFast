package com.edufast.infrastructure.persistence.entity;

import jakarta.persistence.*;

/**
 * Entidad JPA del alumno. El modelo de negocio puro es domain/model/Student.
 */
@Entity
@Table(name = "students")
public class StudentEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String name;

    @Column(unique = true, nullable = false)
    private String code;

    protected StudentEntity() {
    }

    public StudentEntity(Long id, String name, String code) {
        this.id = id;
        this.name = name;
        this.code = code;
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getCode() {
        return code;
    }
}
